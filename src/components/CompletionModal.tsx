import React, { useEffect } from 'react';
import { StudySession } from '../types';
import confetti from 'canvas-confetti';
import { 
  Sparkles, 
  Trophy, 
  X,
  CheckCircle2,
  Clock,
  ListTodo
} from 'lucide-react';

interface CompletionModalProps {
  session: StudySession;
  summaryText: string;
  onClose: () => void;
  onNewSession: () => void;
}

export const CompletionModal: React.FC<CompletionModalProps> = ({
  session,
  summaryText,
  onClose,
  onNewSession,
}) => {
  // Fire celebration confetti on open
  useEffect(() => {
    try {
      confetti({
        particleCount: 75,
        spread: 60,
        origin: { y: 0.6 },
        colors: ['#6366f1', '#06b6d4', '#10b981', '#f59e0b'],
      });
    } catch (e) {
      // Ignore if canvas-confetti is not loaded
    }
  }, []);

  // Escape key handler
  useEffect(() => {
    const handleKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        onClose();
      }
    };
    window.addEventListener('keydown', handleKey);
    return () => window.removeEventListener('keydown', handleKey);
  }, [onClose]);

  const completed = session.tasks.filter(t => t.status === 'completed');
  const remaining = session.tasks.filter(t => t.status !== 'completed');
  const completedMinutes = completed.reduce((sum, t) => sum + t.estimatedMinutes, 0);
  const remainingMinutes = remaining.reduce((sum, t) => sum + t.estimatedMinutes, 0);

  return (
    <div 
      className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-navy-950/80 backdrop-blur-sm animate-fade-in"
      onClick={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
      role="dialog"
      aria-modal="true"
      aria-labelledby="completion-title"
    >
      <div className="bg-navy-900 border border-slate-700/80 rounded-2xl max-w-lg w-full shadow-2xl overflow-hidden flex flex-col">
        {/* Modal Header */}
        <div className="p-5 bg-gradient-to-r from-indigo-950 via-navy-800 to-navy-900 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-amber-500/20 border border-amber-500/40 flex items-center justify-center text-amber-400 shadow-sm">
              <Trophy className="w-5 h-5 text-amber-400" />
            </div>
            <div>
              <h3 id="completion-title" className="text-base font-bold text-white">Study Session Concluded</h3>
              <p className="text-xs text-slate-300">
                Grounded progress summary generated by FocusFlow AI
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            aria-label="Close completion modal"
            className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors focus:outline-none focus:ring-2 focus:ring-accent"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-5 space-y-4 max-h-[60vh] overflow-y-auto">
          {/* Quick Metrics Cards */}
          <div className="grid grid-cols-3 gap-2.5 text-center">
            <div className="p-3 bg-navy-850 border border-slate-800 rounded-xl shadow-sm">
              <div className="flex items-center justify-center gap-1 text-slate-400 mb-1">
                <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
                <span className="text-[10px] uppercase font-bold">Done</span>
              </div>
              <span className="text-lg font-bold text-emerald-400">
                {completed.length} / {session.tasks.length}
              </span>
              <span className="text-xs text-slate-400 block mt-0.5">Tasks</span>
            </div>

            <div className="p-3 bg-navy-850 border border-slate-800 rounded-xl shadow-sm">
              <div className="flex items-center justify-center gap-1 text-slate-400 mb-1">
                <Clock className="w-3.5 h-3.5 text-cyan-400" />
                <span className="text-[10px] uppercase font-bold">Time</span>
              </div>
              <span className="text-lg font-bold text-cyan-400">
                ~{completedMinutes}m
              </span>
              <span className="text-xs text-slate-400 block mt-0.5">Completed</span>
            </div>

            <div className="p-3 bg-navy-850 border border-slate-800 rounded-xl shadow-sm">
              <div className="flex items-center justify-center gap-1 text-slate-400 mb-1">
                <ListTodo className="w-3.5 h-3.5 text-indigo-400" />
                <span className="text-[10px] uppercase font-bold">Remaining</span>
              </div>
              <span className="text-lg font-bold text-slate-200">
                {remaining.length} ({remainingMinutes}m)
              </span>
              <span className="text-xs text-slate-400 block mt-0.5">Unfinished</span>
            </div>
          </div>

          {/* Formatted summary text */}
          <div className="p-4 bg-navy-950/90 border border-slate-800/90 rounded-xl text-xs text-slate-200 leading-relaxed font-mono whitespace-pre-wrap">
            {summaryText}
          </div>
        </div>

        {/* Modal Footer */}
        <div className="p-4 border-t border-slate-800 bg-navy-850/80 flex items-center justify-between gap-3">
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-lg border border-slate-700 bg-navy-800 hover:bg-slate-700 text-slate-300 text-xs font-semibold transition-colors active:scale-95"
          >
            Review Session
          </button>

          <button
            onClick={onNewSession}
            className="px-4 py-2 rounded-lg bg-accent hover:bg-accent-hover text-white text-xs font-bold flex items-center gap-2 shadow-md shadow-accent/20 transition-all active:scale-95"
          >
            <Sparkles className="w-4 h-4" />
            <span>Start New Plan</span>
          </button>
        </div>
      </div>
    </div>
  );
};
