import React, { useEffect } from 'react';
import { StudySession } from '../types';
import confetti from 'canvas-confetti';
import { 
  Sparkles, 
  Trophy, 
  X 
} from 'lucide-react';

interface CompletionModalProps {
  session: StudySession;
  summaryText: string;
  onClose: () => void;
  onNewSession: () => void;
}

export const CompletionModal: React.FC<CompletionModalProps> = ({
  session,
  summaryText,
  onClose,
  onNewSession,
}) => {
  // Fire celebration confetti on open
  useEffect(() => {
    try {
      confetti({
        particleCount: 80,
        spread: 60,
        origin: { y: 0.6 },
        colors: ['#6366f1', '#06b6d4', '#10b981', '#f59e0b'],
      });
    } catch (e) {
      // Ignore if canvas-confetti is not loaded
    }
  }, []);

  const completed = session.tasks.filter(t => t.status === 'completed');
  const remaining = session.tasks.filter(t => t.status !== 'completed');
  const completedMinutes = completed.reduce((sum, t) => sum + t.estimatedMinutes, 0);

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-navy-950/80 backdrop-blur-sm animate-fade-in">
      <div className="bg-navy-900 border border-slate-700 rounded-2xl max-w-lg w-full shadow-2xl overflow-hidden flex flex-col">
        {/* Modal Header */}
        <div className="p-5 bg-gradient-to-r from-indigo-950 via-navy-800 to-navy-900 border-b border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-indigo-600/20 border border-indigo-500/40 flex items-center justify-center text-cyan-400">
              <Trophy className="w-5 h-5 text-amber-400" />
            </div>
            <div>
              <h3 className="text-base font-bold text-white">Study Session Completed</h3>
              <p className="text-xs text-slate-400">
                Grounded progress summary generated by FocusFlow AI
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-5 space-y-4 max-h-[60vh] overflow-y-auto">
          {/* Quick Metrics Cards */}
          <div className="grid grid-cols-3 gap-2 text-center">
            <div className="p-3 bg-navy-850 border border-slate-800 rounded-xl">
              <span className="text-[10px] uppercase font-bold text-slate-400 block mb-1">
                Completed
              </span>
              <span className="text-lg font-bold text-emerald-400">
                {completed.length} / {session.tasks.length}
              </span>
              <span className="text-[10px] text-slate-400 block mt-0.5">Tasks</span>
            </div>

            <div className="p-3 bg-navy-850 border border-slate-800 rounded-xl">
              <span className="text-[10px] uppercase font-bold text-slate-400 block mb-1">
                Study Time
              </span>
              <span className="text-lg font-bold text-cyan-400">
                ~{completedMinutes}m
              </span>
              <span className="text-[10px] text-slate-400 block mt-0.5">Actual Spent</span>
            </div>

            <div className="p-3 bg-navy-850 border border-slate-800 rounded-xl">
              <span className="text-[10px] uppercase font-bold text-slate-400 block mb-1">
                Remaining
              </span>
              <span className="text-lg font-bold text-slate-300">
                {remaining.length}
              </span>
              <span className="text-[10px] text-slate-400 block mt-0.5">Pending Tasks</span>
            </div>
          </div>

          {/* Formatted summary text */}
          <div className="p-3.5 bg-navy-950/80 border border-slate-800 rounded-xl text-xs text-slate-300 leading-relaxed font-mono whitespace-pre-wrap">
            {summaryText}
          </div>
        </div>

        {/* Modal Footer */}
        <div className="p-4 border-t border-slate-800 bg-navy-850/80 flex items-center justify-between gap-3">
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-lg border border-slate-700 bg-navy-800 hover:bg-slate-700 text-slate-300 text-xs font-medium transition-colors"
          >
            Review Session
          </button>

          <button
            onClick={onNewSession}
            className="px-4 py-2 rounded-lg bg-accent hover:bg-accent-hover text-white text-xs font-semibold flex items-center gap-2 shadow-md shadow-accent/20 transition-all"
          >
            <Sparkles className="w-4 h-4" />
            <span>Start New Plan</span>
          </button>
        </div>
      </div>
    </div>
  );
};
